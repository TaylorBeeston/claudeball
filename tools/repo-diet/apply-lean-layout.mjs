#!/usr/bin/env node
/**
 * Applies the lean repository layout to the checkout it runs in (idempotent; review with `git diff` and commit it yourself):
 *   - .gitignore: the build intermediates of tools/repo-diet/intermediates.txt (and dist-intermediates/)
 *   - .gitattributes: binary assets are `binary -diff` (no text diffs / merges of GLBs, textures, archives)
 *   - git rm --cached of intermediates that are still tracked (the files stay on disk)
 *   - vite.config.ts: the derived-asset freshness check skips sources that are not present (they are fetched only for asset work)
 *   - scripts/derive-assets.mjs: says to run `npm run assets:fetch` when the plain player exports are missing
 *   - package.json: `assets:fetch`, `assets:pack`, `size:check`
 *   - .github/workflows/deploy.yml: checkout with fetch-depth 2 and a size check before the build
 *   node tools/repo-diet/apply-lean-layout.mjs
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim();
const P = (...p) => path.join(root, ...p);
const edit = (f, fn) => {
  const before = fs.readFileSync(P(f), 'utf8');
  const after = fn(before);
  if (after !== before) { fs.writeFileSync(P(f), after); console.log(`edited ${f}`); }
};

// .gitignore
const rules = fs.readFileSync(P('tools/repo-diet/intermediates.txt'), 'utf8').split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));
const globs = [
  '/assets/players/*.glb', '/assets/players/lod1/', '/assets/field.glb', '/assets/stadium.glb', '/assets/ball.glb', '/assets/bat.glb', '/assets/bat_donut.glb',
  '/assets/optimized/lod1/', '/assets/optimized/lod/', '/assets/tex/', '/dist-intermediates/',
  ...['home', 'away', 'home_of', 'away_of', 'home_1b', 'away_1b', 'batter', 'catcher', 'manager'].flatMap((r) => [`/assets/optimized/players/player_${r}.glb`, `/assets/optimized/players_1k/player_${r}.glb`]),
];
void rules;
edit('.gitignore', (s) => (s.includes('# build intermediates (lean layout') ? s : `${s.trimEnd()}\n\n# build intermediates (lean layout, docs/repo-size.md): regenerated by the Blender scripts / optimize.sh / assets:derive, or \`npm run assets:fetch\`\n${globs.join('\n')}\n`));

// .gitattributes
const attrs = ['*.glb binary -diff', '*.ktx2 binary -diff', '*.webp binary -diff', '*.png binary -diff', '*.jpg binary -diff', '*.jpeg binary -diff', '*.hdr binary -diff', '*.npz binary -diff', '*.woff2 binary -diff', '*.tar.gz binary -diff', '*.wav binary -diff', '*.mp3 binary -diff', '*.ogg binary -diff'];
if (!fs.existsSync(P('.gitattributes'))) fs.writeFileSync(P('.gitattributes'), '');
edit('.gitattributes', (s) => (s.includes('*.glb binary') ? s : `${s.trimEnd()}${s.trim() ? '\n' : ''}# binary assets: never diffed or merged as text (docs/repo-size.md)\n${attrs.join('\n')}\n`));

// untrack intermediates (files stay on disk)
const tracked = execFileSync('git', ['ls-files'], { cwd: root, encoding: 'utf8' }).split('\n').filter(Boolean);
const re = rules.map((l) => (l.startsWith('regex:') ? new RegExp(l.slice(6)) : { test: (p) => p.startsWith(l) }));
const drop = tracked.filter((p) => re.some((r) => r.test(p)));
if (drop.length) {
  for (let i = 0; i < drop.length; i += 200) execFileSync('git', ['rm', '-q', '--cached', '--', ...drop.slice(i, i + 200)], { cwd: root });
  console.log(`untracked ${drop.length} intermediates (still on disk)`);
}

// vite.config.ts: skip missing derived-asset sources
edit('vite.config.ts', (s) =>
  s.replace(
    ".filter(([rel, sha]) => crypto.createHash('sha1').update(fs.readFileSync(path.join(src, rel))).digest('hex') !== sha)",
    "// sources that are not here (intermediates are fetched only for asset work: npm run assets:fetch) cannot be checked\n          .filter(([rel]) => fs.existsSync(path.join(src, rel)))\n          .filter(([rel, sha]) => crypto.createHash('sha1').update(fs.readFileSync(path.join(src, rel))).digest('hex') !== sha)",
  ),
);

// derive-assets.mjs: clear message when the plain exports are missing
edit('scripts/derive-assets.mjs', (s) =>
  s.includes('assets:fetch')
    ? s
    : s.replace(
        "const derived = { sources: {} };",
        "const derived = { sources: {} };\nconst missing = shipped.players_1k.filter((f) => !fs.existsSync(A('players', `${f}.glb`)));\nif (missing.length) throw new Error(`plain player exports missing (${missing.join(', ')}): run \\`npm run assets:fetch\\` or the Blender build first (docs/repo-size.md)`);",
      ),
);

// package.json scripts
edit('package.json', (s) => {
  const j = JSON.parse(s);
  j.scripts['assets:fetch'] ??= 'node tools/repo-diet/assets-fetch.mjs';
  j.scripts['assets:pack'] ??= 'node tools/repo-diet/assets-fetch.mjs --pack';
  j.scripts['size:check'] ??= 'node tools/repo-diet/check-size.mjs';
  return JSON.stringify(j, null, 2) + '\n';
});

// deploy workflow: size check before the build
edit('.github/workflows/deploy.yml', (s) =>
  s.includes('check-size.mjs')
    ? s
    : s
        .replace('      - uses: actions/checkout@v7\n', '      - uses: actions/checkout@v7\n        with:\n          fetch-depth: 2   # the size check compares the commit with its parent\n')
        .replace('      - run: npm ci\n', '      - name: Repository size check (no build intermediates, no huge files / commits; docs/repo-size.md)\n        run: node tools/repo-diet/check-size.mjs\n\n      - run: npm ci\n'),
);
console.log('lean layout applied: review `git status` / `git diff --cached`, then commit');
